const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const {createRequire} = require('node:module');
const {spawnSync} = require('node:child_process');
const root = process.env.PRODUCT_ROOT;
const requireProduct = createRequire(path.join(root, 'package.json'));
const asar = requireProduct('@electron/asar');
const release = path.join(root, 'release');
const resources = path.join(release, 'win-unpacked/resources');
const metadata = JSON.parse(asar.extractFile(path.join(resources, 'app.asar'), 'package.json').toString());
assert.equal(metadata.version, '1.23.0');
assert.equal(Object.hasOwn(metadata, 'emberUpdateChannel'), false);
assert.equal(metadata.build?.win?.verifyUpdateCodeSignature ?? true, true);
assert.equal(fs.existsSync(path.join(release, 'latest.yml')), false);
assert.equal(fs.existsSync(path.join(resources, 'app-update.yml')), false);
const pe = file => {
  const b = fs.readFileSync(file);
  assert.equal(b.toString('ascii', 0, 2), 'MZ');
  const offset = b.readUInt32LE(0x3c);
  assert.equal(b.toString('ascii', offset, offset + 4), 'PE\0\0');
  assert.equal(b.readUInt16LE(offset + 4), 0x8664);
  console.log('PE x64 verified: ' + file);
};
for (const file of ['win-unpacked/Ember.exe', 'win-unpacked/resources/kiln.exe', 'tinder-cli.exe']) pe(path.join(release, file));
const result = spawnSync(path.join(release, 'tinder-cli.exe'), ['help'], {encoding:'utf8', timeout:20000, cwd:process.env.RUNNER_TEMP,
  env:{SystemRoot:process.env.SystemRoot, HOME:process.env.RUNNER_TEMP, USERPROFILE:process.env.RUNNER_TEMP}});
assert.equal(result.status, 0, result.stdout + result.stderr);
assert.match(result.stdout, /serve/);
console.log('Actual Tinder CLI help passed (no server or provider traffic).');
assert.match(fs.readFileSync(path.join(release, 'installed-validation.txt'), 'utf8'), /^PASS:/);
const names = fs.readdirSync(release).filter(n => /-windows-x64-setup\.(exe|zip)$/.test(n));
assert.equal(names.some(n => n.endsWith('.exe')), true);
assert.equal(names.some(n => n.endsWith('.zip')), true);
fs.copyFileSync(path.join(release, 'tinder-cli.exe'), path.join(release, 'tinder-windows-x64.exe'));
names.push('tinder-windows-x64.exe');
fs.writeFileSync(path.join(release, 'SHA256SUMS-windows.txt'), names.sort().map(n => crypto.createHash('sha256').update(fs.readFileSync(path.join(release,n))).digest('hex') + '  ' + n + '\n').join(''));
fs.writeFileSync(path.join(release, 'MANUAL-WINDOWS.txt'), `Ember 1.23.0 unsigned manual Windows x64 build\nProduct commit: 2c46cb55018f5113300f4376caffc7a921e3cf30\nValidation/overlay commit recorded by GitHub Actions run head SHA.\nBuilder override: publish=null; extraMetadata={}; no stable marker, latest.yml, or app-update.yml.\nRuntime signature verification remains enabled in product source.\nWindows may show SmartScreen or Unknown publisher because this installer is unsigned. Only proceed if you trust this download and its checked SHA-256.\nAutomatic updates are disabled. Download future releases manually, quit Ember, replace/install, and reopen; preserve your data folder.\nNative launch uses isolated profiles and owned loopback local-runtime fixtures; no live sign-in or provider inference is requested. Compiled OAuth uses a synthetic exchange. This is not a claim that all application/OS networking was blocked.\nSigned A-to-B update/publisher rejection are not applicable to this manual distribution and are not claimed.\nSee installed-validation.txt for the required native silent NSIS installation, installed launch, owned Kiln shutdown, silent uninstall and retained synthetic data checks.\n`);
console.log('Packaged version, absent stable marker/feed, actual CLI, PE x64 and SHA256SUMS verified.');
