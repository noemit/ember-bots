import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, mkdtempSync, rmSync } from 'node:fs';
import { join, basename } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { parse } from 'yaml';

export const required = {
  macos: ['Ember-macos-arm64.dmg', 'Ember-macos-arm64.zip', 'tinder-macos-arm64'],
  windows: ['Ember-windows-x64-setup.exe', 'Ember-windows-x64.zip', 'tinder-windows-x64.exe'],
  linux: ['Ember-linux-x64.AppImage', 'Ember-linux-x64.tar.gz', 'tinder-linux-x64'],
};
const channels = { macos: 'latest-mac.yml', windows: 'latest.yml', linux: 'latest-linux.yml' };
const hash = (bytes, algorithm, encoding = 'hex') => createHash(algorithm).update(bytes).digest(encoding);
function assert(ok, message) { if (!ok) throw new Error(message); }
export function validateVersion(version, contract = true) {
  assert(/^\d+\.\d+\.\d+$/.test(version), 'Use a stable semantic version, without v or prerelease suffix.');
  const [major, minor, patch] = version.split('.').map(Number);
  assert(!contract || major > 1 || major === 1 && (minor > 23 || minor === 23 && patch >= 1), 'The new contract starts at 1.23.1; never rewrite older releases.');
}
export function platformFiles(dir, platform, windows = 'manual') {
  assert(Object.hasOwn(required, platform), 'Choose macos, windows or linux.');
  assert(['signed', 'manual'].includes(windows), 'Choose signed or manual Windows distribution.');
  const files = [...required[platform]];
  if (platform !== 'windows' || windows === 'signed') files.push(channels[platform]);
  else assert(!readdirSync(dir).includes('latest.yml'), 'Manual Windows distribution must not advertise latest.yml. Stage only manual assets.');
  // External maps retain exactly the artifact name generated by builder.
  files.push(...readdirSync(dir).filter(name => required[platform].some(asset => name === asset + '.blockmap')));
  // Pinned builder emits these external maps. Require them, not just whatever was staged.
  const maps = platform === 'macos' ? required.macos.slice(0, 2).map(name => name + '.blockmap')
    : platform === 'windows' ? [required.windows[0] + '.blockmap'] : [];
  for (const map of maps) assert(files.includes(map), `Missing generated blockmap ${map}.`);
  for (const file of files) readFileSync(join(dir, file));
  return files.sort();
}
export function validateMetadata(dir, platform, version, windows = 'manual') {
  const files = platformFiles(dir, platform, windows);
  if (!files.includes(channels[platform])) return;
  const metadata = parse(readFileSync(join(dir, channels[platform]), 'utf8'));
  assert(metadata.version === version, `${platform}: metadata version must equal release version.`);
  assert(Array.isArray(metadata.files) && metadata.files.length, `${platform}: metadata needs files.`);
  const expected = platform === 'macos' ? required.macos.slice(0, 2) : [required[platform][0]];
  for (const name of expected) assert(metadata.files.some(file => file.url === name), `${platform}: metadata must reference ${name}.`);
  for (const file of metadata.files) {
    assert(typeof file.url === 'string' && basename(file.url) === file.url && required[platform].includes(file.url), `${platform}: metadata URL must be a final contract filename.`);
    const bytes = readFileSync(join(dir, file.url));
    assert(file.size === bytes.length && file.sha512 === hash(bytes, 'sha512', 'base64'), `${file.url}: metadata size or SHA-512 differs from final bytes.`);
  }
  if (platform === 'linux') {
    const appImage = metadata.files.find(file => file.url === required.linux[0]);
    assert(Number.isInteger(appImage.blockMapSize) && appImage.blockMapSize > 0 && appImage.blockMapSize < appImage.size, 'AppImage metadata needs its embedded block map size.');
  }
  const legacy = metadata.files.find(file => file.url === metadata.path);
  assert(legacy && legacy.sha512 === metadata.sha512, `${platform}: legacy path/SHA-512 must match files.`);
  if (platform === 'macos') assert(metadata.path === required.macos[1], 'Mac legacy path must select ZIP.');
}
export function checksums(dir, platform, version, windows = 'manual', verify = false) {
  validateVersion(version, false); // CI can rehearse names without bumping the source version.
  validateMetadata(dir, platform, version, windows);
  const content = platformFiles(dir, platform, windows).map(file => `${hash(readFileSync(join(dir, file)), 'sha256')}  ${file}\n`).join('');
  const path = join(dir, `SHA256SUMS-${platform}.txt`);
  if (verify) assert(readFileSync(path, 'utf8').replace(/\r\n/g, '\n') === content, `${platform}: checksum manifest differs from final upload set.`);
  else writeFileSync(path, content);
}
export function audit(dir, version, windows) {
  validateVersion(version);
  assert(['signed', 'manual'].includes(windows), 'Audit requires an explicit signed or manual Windows policy.');
  for (const platform of Object.keys(required)) checksums(dir, platform, version, windows, true);
  const allowed = new Set(Object.keys(required).flatMap(platform => [...platformFiles(dir, platform, windows), `SHA256SUMS-${platform}.txt`]));
  for (const name of readdirSync(dir)) assert(allowed.has(name), `Unexpected release asset ${name}; review the contract before publishing.`);
}

// Download the actual draft assets, audit, then explicitly promote. Never uploads/replaces assets.
export function promote(version, windows, gh = (...args) => execFileSync('gh', args, { encoding: 'utf8' })) {
  validateVersion(version);
  const repo = 'noemit/ember-bots';
  const tag = `v${version}`;
  const get = () => JSON.parse(gh('api', `repos/${repo}/releases/tags/${tag}`));
  const release = get();
  assert(release.draft && !release.prerelease && release.name === `Ember ${version}`, 'Promotion requires a non-prerelease draft titled Ember <version>. Published assets are immutable.');
  const dir = mkdtempSync(join(tmpdir(), 'ember-release-audit-'));
  try {
    gh('release', 'download', tag, '--repo', repo, '--dir', dir);
    audit(dir, version, windows);
    // Refuse a concurrently replaced upload set; GitHub asset IDs/digests change on replacement.
    const again = get();
    assert(again.draft && !again.prerelease && again.name === release.name && JSON.stringify(again.assets) === JSON.stringify(release.assets), 'Draft changed during audit; audit again before promotion.');
    gh('api', '--method', 'PATCH', `repos/${repo}/releases/${release.id}`, '-F', 'draft=false', '-F', 'prerelease=false', '-f', 'make_latest=true');
  } finally { rmSync(dir, { recursive: true, force: true }); }
}
