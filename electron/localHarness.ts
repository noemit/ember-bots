/**
 * The local harness, started by Ember itself.
 *
 * Installing the desktop app used to leave you with a control room and nothing to control on the
 * machine you had just set it up on: it could only reach Kiln if one was already running, or if you
 * cloned this repository and ran the CLI. A desktop app that needs a terminal before it can show a
 * single conversation has not been installed, it has been unpacked.
 *
 * So the app ships the harness. On first launch it starts the bundled Kiln on loopback, adopts the
 * token it writes, and lists it as an ordinary endpoint — which means every existing piece of the
 * app (instances, streams, polling, crew strip) keeps working unchanged. Nothing here is a second
 * way to talk to a host; it is one way to *have* a host.
 *
 * The rules this follows:
 *
 * - **A local harness is ours only if we started it.** If something already answers on the port —
 *   a Kiln from `tinder setup --service`, or a container — we attach to it and never own its
 *   lifecycle. Quitting Ember must not take down a host that was running before it launched.
 * - **Never two of them.** Two harnesses on one data home would open one SQLite database twice,
 *   which is a corruption risk, not a bug report. The lock file (`<home>/ember-harness.lock`)
 *   decides who owns it, and a stale lock from a crashed parent is reclaimed.
 * - **A failure is a sentence, not a stack.** The renderer shows why the bundled host did not start,
 *   because "no instances" for a missing binary is the exact dead end the copy rules forbid.
 */
import { spawn, type ChildProcess } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { generateToken } from './tokenWords';

/** Fixed so the app and the CLI agree where a local harness listens and keeps its data. */
export const LOCAL_HARNESS_PORT = 3002;
export const HARNESS_START_TIMEOUT_MS = 20_000;
const POLL_INTERVAL_MS = 250;

export type LocalHarnessState =
  /** A harness answered before we tried to start one: it is not ours to stop. */
  | { kind: 'attached'; url: string; token: string; version?: string }
  /** We started it, and it is answering. */
  | { kind: 'started'; url: string; token: string; version?: string }
  /**
   * We started it, and this run replaced its token (a rotation).
   *
   * A separate kind rather than reusing `started`, so the endpoint merge keeps a rotated harness in
   * the list. The merge only adds the *started* harness because a token read from settings might be
   * stale — but after a rotation the harness on this port is running with the token that is now on
   * disk, and dropping it would make the host vanish from the rail the moment it was given a new
   * password.
   */
  | { kind: 'restarted'; url: string; token: string; version?: string }
  /** The user turned it off in settings. */
  | { kind: 'disabled' }
  /** The binary is not where the installer put it (a dev checkout, a repack). */
  | { kind: 'missing'; binaryPath: string }
  /** It was started and did not answer within the timeout, or it exited. */
  | { kind: 'failed'; reason: string };

export type LocalHarnessOptions = {
  /** Directory holding the bundled binary (`Contents/Resources` on macOS). */
  resourcesDir: string;
  /** Where the binary is, relative to `resourcesDir`. Overridable so a dev run can point anywhere. */
  binaryName?: string;
  /** `<home>` for the harness; `~/.ember` unless overridden. */
  home?: string;
  port?: number;
  /** Skip starting even when the binary exists (Settings → Instances, "Run Kiln on this computer"). */
  disabled?: boolean;
  logFile?: string;
  /** Test seam: how to spawn. Defaults to `spawn` with the bundled binary. */
  spawn?: (command: string, args: string[], options: Record<string, unknown>) => ChildProcess;
  /** Test seam: the loopback probe. */
  probe?: (url: string) => Promise<{ ok: boolean; version?: string }>;
  /** Test seam: where the harness's credential is read from. Defaults to `readHarnessToken(home)`. */
  readToken?: () => string | undefined;
  /**
   * A token to install before starting. Written to the data home *first*, so the harness boots with
   * it instead of generating its own — which is what makes a rotation one step from disk's point of
   * view. Omitted on a normal launch: an existing token is used, and a missing one is generated by
   * the harness as it always was.
   */
  token?: string;
  now?: () => number;
};

type LockFile = { pid: number; startedAt: number };

const lockPathFor = (home: string): string => path.join(home, 'ember-harness.lock');

const readLock = (home: string): LockFile | null => {
  try {
    const raw = JSON.parse(fs.readFileSync(lockPathFor(home), 'utf8')) as Partial<LockFile>;
    if (!Number.isSafeInteger(raw.pid) || typeof raw.startedAt !== 'number') return null;
    return { pid: raw.pid as number, startedAt: raw.startedAt };
  } catch {
    return null;
  }
};

/** Whether a pid is a live process. `EPERM` is a process that exists and is not ours to signal. */
export const isProcessAlive = (pid: number): boolean => {
  if (!Number.isSafeInteger(pid) || pid <= 1) return false;
  if (pid === process.pid) return true;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code === 'EPERM';
  }
};

const writeLock = (home: string, pid: number, at: number): void => {
  try {
    fs.mkdirSync(home, { recursive: true });
    fs.writeFileSync(lockPathFor(home), `${JSON.stringify({ pid, startedAt: at })}\n`, { mode: 0o600 });
  } catch {
    // A missing lock is a smaller problem than refusing to start: it only weakens the "never two
    // of them" guard, which is still enforced by the port probe.
  }
};

const clearLock = (home: string): void => {
  try {
    fs.unlinkSync(lockPathFor(home));
  } catch {
    // Already gone.
  }
};

/** The default home, matching the CLI and the harness (`EMBER_HOME`, then `~/.ember`). */
export const defaultHarnessHome = (
  env: Readonly<Record<string, string | undefined>> = process.env,
  homedir: string = os.homedir()
): string => {
  const override = env.EMBER_HOME?.trim() || env.HEARTH_HOME?.trim();
  return override ? path.resolve(override) : path.join(homedir, '.ember');
};

/** The harness writes `hearth.token`; the CLI keeps `ember.token` beside it. Either will do. */
export const readHarnessToken = (home: string): string | undefined => {
  for (const name of ['hearth.token', 'ember.token']) {
    try {
      const value = fs.readFileSync(path.join(home, name), 'utf8').trim();
      if (value) return value;
    } catch {
      // Try the next name.
    }
  }
  return undefined;
};

/**
 * Whether a harness is *usable*, not merely answering.
 *
 * `/health` answering and a token being readable are two different facts, and the harness makes them
 * true at different moments: it binds the port and starts answering, then writes `hearth.token`.
 * The first client to poll in that window saw a healthy host and recorded an **empty** token, so the
 * app listed a connection that answered `/health` and rejected everything else with 401 — a failure
 * nothing logged, because from the harness's side nothing was wrong.
 *
 * So "ready" means both: it answers *and* we hold the credential it answers to. A host that is
 * already running and whose token we cannot read is not adopted either — an adopted endpoint with no
 * token is the same 401 wearing a different label.
 */
export const harnessIsReady = async (
  probe: (url: string) => Promise<{ ok: boolean; version?: string }>,
  readToken: () => string | undefined,
  url: string
): Promise<{ ready: boolean; version?: string; token?: string }> => {
  const answer = await probe(url);
  if (!answer.ok) return { ready: false };
  const token = readToken()?.trim();
  if (!token) return { ready: false };
  return { ready: true, token, ...(answer.version ? { version: answer.version } : {}) };
};

const defaultProbe = async (
  url: string,
  token: string | undefined
): Promise<{ ok: boolean; version?: string }> => {
  try {
    const response = await fetch(`${url}/health`, {
      headers: token ? { authorization: `Bearer ${token}` } : {},
      signal: AbortSignal.timeout(1_500),
    });
    if (!response.ok) return { ok: false };
    const body = (await response.json().catch(() => ({}))) as { version?: unknown };
    return { ok: true, ...(typeof body.version === 'string' ? { version: body.version } : {}) };
  } catch {
    return { ok: false };
  }
};

/**
 * What the bundled binary is called on each platform. `electron-builder` copies it to the app's
 * resources directory, so the path is stable inside an installed app and absent in a dev checkout —
 * where `bun run dev` is expected to talk to a harness the developer started themselves.
 */
export const binaryNameFor = (platform: NodeJS.Platform = process.platform): string =>
  platform === 'win32' ? 'kiln.exe' : 'kiln';

export const bundledBinaryPath = (
  resourcesDir: string,
  platform: NodeJS.Platform = process.platform,
  binaryName: string = binaryNameFor(platform)
): string => path.join(resourcesDir, binaryName);

/**
 * Start (or adopt) the local harness.
 *
 * Returns as soon as the harness answers, or with a state that says why it does not. It never
 * throws: a desktop app that refuses to open because its optional dependency failed is worse than
 * one that opens and explains.
 */
/**
 * Write a token to the data home, both names, mode 0600.
 *
 * The harness and the CLI each look for two filenames (`hearth.token` first, then `ember.token`), so
 * a token written to only one of them can be silently overridden: the harness finds the other file's
 * older value and keeps using it while the UI shows the new one. Both, always.
 */
export const writeHarnessToken = (home: string, token: string): void => {
  fs.mkdirSync(home, { recursive: true, mode: 0o700 });
  for (const name of ['hearth.token', 'ember.token']) {
    const file = path.join(home, name);
    fs.writeFileSync(file, token + '\n', { encoding: 'utf8', mode: 0o600 });
    try {
      // Windows has no POSIX mode bits, and an existing file keeps its old mode through a write.
      fs.chmodSync(file, 0o600);
    } catch {
      // Not supported on this platform.
    }
  }
};

/**
 * Whether this app may replace the harness's token: it must be the harness we started.
 *
 * `attached` is the distinction that matters. That host was already running when Ember launched, or it
 * is the service Tinder installed; its token is not Ember's to change. Writing a new one would lock
 * out every other client of that host without stopping its process, and the change would only take
 * effect on a restart Ember does not control. `started` and `restarted` are both ours: one process,
 * one data home, one record of which token it holds.
 */
export const canManageLocalToken = (state: LocalHarnessState): boolean =>
  state.kind === 'started' || state.kind === 'restarted';

/**
 * The local harness as an endpoint, or null when there is nothing to list.
 *
 * This is the function that decides whether "This computer" exists in the UI, so it answers for the
 * two ways a local host becomes real: a state that is answering, or — when nothing has answered yet
 * in this launch — a token already on disk. The second case matters more than it looks: the first
 * `getSettings()` call lands before `startLocalHarness` has finished, and returning null there left
 * Settings → Instances empty on exactly the launch where someone is looking at it.
 *
 * `localHarnessEnabled: false` means the person turned the bundled host off; this then returns null
 * and settings-only endpoints stand alone.
 */
export const localHarnessEndpoint = (options: {
  state: LocalHarnessState;
  enabled: boolean;
  home: string;
  readToken?: () => string | undefined;
}): { url: string; token: string } | null => {
  if (!options.enabled) return null;
  if (isActiveHarness(options.state)) {
    return { url: options.state.url, token: options.state.token };
  }
  const read = options.readToken ?? (() => readHarnessToken(options.home));
  const token = read()?.trim();
  if (!token) return null;
  return { url: `http://127.0.0.1:${LOCAL_HARNESS_PORT}`, token };
};

/** How long a stop-and-restart is allowed to take before it is reported as a failure. */
export const HARNESS_RESTART_TIMEOUT_MS = 45_000;

/**
 * The token a running harness currently answers to, read from disk.
 *
 * Read rather than trusted from `state.token`: after a rotation the state object is replaced, but a
 * person who edited the file by hand (or a harness that wrote its own on first boot) has a token
 * that only the file knows. The file is the thing the harness actually consulted.
 */
export const harnessTokenOnDisk = (home: string): string | undefined => readHarnessToken(home);

/** Four words, from the same generator the harness and the CLI use. */
export const generateHarnessToken = (): string => generateToken();

export const startLocalHarness = async (options: LocalHarnessOptions): Promise<{
  state: LocalHarnessState;
  stop: () => void;
}> => {
  const port = options.port ?? LOCAL_HARNESS_PORT;
  const url = `http://127.0.0.1:${port}`;
  const home = options.home ?? defaultHarnessHome();
  const probe = options.probe ?? ((target: string) => defaultProbe(target, readHarnessToken(home)));
  const now = options.now ?? Date.now;
  let child: ChildProcess | undefined;
  let stopping = false;

  const stop = (): void => {
    stopping = true;
    if (!child) return;
    try {
      child.kill('SIGTERM');
    } catch {
      // Already gone.
    }
    const owned = child;
    child = undefined;
    // The harness honours SIGTERM and closes its database; a grace period rather than SIGKILL,
    // because a killed harness can leave a hot journal behind.
    const timer = setTimeout(() => {
      try {
        owned.kill('SIGKILL');
      } catch {
        // Already gone.
      }
    }, 5_000);
    timer.unref?.();
    clearLock(home);
  };

  const readToken = options.readToken ?? (() => readHarnessToken(home));

  // 1. Something already answering is not ours. This is the service the CLI installed, a container,
  //    or a second Ember window; either way, quitting must not stop it. It is only adopted when we
  //    can authenticate to it — a host whose answer we cannot use is not a host we can list.
  const existing = await harnessIsReady(probe, readToken, url);
  if (existing.ready) {
    return {
      state: { kind: 'attached', url, token: existing.token ?? '', ...(existing.version ? { version: existing.version } : {}) },
      stop: () => {},
    };
  }

  if (options.disabled === true) return { state: { kind: 'disabled' }, stop: () => {} };

  const binaryPath = bundledBinaryPath(options.resourcesDir, process.platform, options.binaryName);
  let present = true;
  try {
    fs.accessSync(binaryPath, fs.constants.X_OK);
  } catch {
    present = false;
  }
  if (!present) return { state: { kind: 'missing', binaryPath }, stop: () => {} };

  // 2. One harness per data home. A live lock means an Ember instance already owns it (and the
  //    probe above says it is not answering yet — starting a second one would open the same SQLite
  //    database twice). A dead lock is from a crash and is reclaimed.
  const lock = readLock(home);
  if (lock && isProcessAlive(lock.pid)) {
    // It may still be booting. Wait for it rather than starting a rival.
    const deadline = now() + HARNESS_START_TIMEOUT_MS;
    while (now() < deadline) {
      const answer = await harnessIsReady(probe, readToken, url);
      if (answer.ready) {
        return {
          state: { kind: 'attached', url, token: answer.token ?? '', ...(answer.version ? { version: answer.version } : {}) },
          stop: () => {},
        };
      }
      await new Promise((resolve) => setTimeout(resolve, POLL_INTERVAL_MS));
    }
    return {
      state: { kind: 'failed', reason: `another Ember is starting the harness (pid ${lock.pid}) and it has not answered after ${HARNESS_START_TIMEOUT_MS / 1000}s` },
      stop: () => {},
    };
  }
  if (lock) clearLock(home);

  // 3. Install the token we were handed, *before* the child exists.
  //
  //    Writing it first is what makes a rotation one operation: the harness reads its credential once
  //    at startup, so the value on disk at boot is the value it will answer to. Written after the
  //    spawn it would race — the harness writes its own token as it boots, and the loser is a host
  //    that 401s against the token the screen is showing.
  if (options.token?.trim()) writeHarnessToken(home, options.token.trim());

  // 4. Start it, with the log on disk so a failure to boot is readable rather than invisible.
  const logPath = options.logFile ?? path.join(home, 'kiln.log');
  try {
    fs.mkdirSync(home, { recursive: true });
    const log = fs.openSync(logPath, 'a');
    fs.writeSync(log, `\n${new Date(now()).toISOString()} Ember starting the bundled harness\n`);
    const spawnFn = options.spawn ?? spawn;
    const spawned = spawnFn(binaryPath, [], {
      env: {
        ...process.env,
        HEARTH_HOME: home,
        EMBER_HOME: home,
        HEARTH_PORT: String(port),
        HEARTH_BIND: '127.0.0.1',
        // The app is not a git checkout, so the build watcher has nothing to watch.
        HEARTH_AUTORELOAD: '0',
      },
      stdio: ['ignore', log, log],
      windowsHide: true,
    });
    spawned.on('exit', () => {
      if (stopping) return;
      clearLock(home);
    });
    child = spawned;
    if (spawned.pid) writeLock(home, spawned.pid, now());
  } catch (error) {
    return {
      state: { kind: 'failed', reason: `the bundled harness could not be started (${error instanceof Error ? error.message : String(error)})` },
      stop: () => {},
    };
  }

  const deadline = now() + HARNESS_START_TIMEOUT_MS;
  while (now() < deadline) {
    if (child?.exitCode !== null && child?.exitCode !== undefined) {
      clearLock(home);
      return {
        state: { kind: 'failed', reason: `the bundled harness exited with code ${child.exitCode} — see ${logPath}` },
        stop,
      };
    }
    // Both facts, not just the port: see `harnessIsReady`.
    const answer = await harnessIsReady(probe, readToken, url);
    if (answer.ready) {
      return {
        state: { kind: 'started', url, token: answer.token ?? '', ...(answer.version ? { version: answer.version } : {}) },
        stop,
      };
    }
    await new Promise((resolve) => setTimeout(resolve, POLL_INTERVAL_MS));
  }
  stop();
  return {
    state: { kind: 'failed', reason: `the bundled harness did not answer on ${url} within ${HARNESS_START_TIMEOUT_MS / 1000}s — see ${logPath}` },
    stop: () => {},
  };
};

/** The sentence the renderer shows for each non-success state, phrased for the reader. */
export const localHarnessNotice = (state: LocalHarnessState, home = defaultHarnessHome()): string | null => {
  switch (state.kind) {
    case 'attached':
    case 'started':
    case 'restarted':
    case 'disabled':
      return null;
    case 'missing':
      return `This copy of Ember did not ship its local agent server (${path.basename(state.binaryPath)} is missing). Add a host in Settings → Instances, or run \`tinder setup\` to install one here.`;
    case 'failed':
      return `The local agent server did not start: ${state.reason}. You can still add a host in Settings → Instances. Log: ${path.join(home, 'kiln.log')}`;
  }
};

/** The endpoints Ember talks to: the configured ones, plus the harness this app started. */
export type HarnessEndpoint = { id: string; label: string; url: string; token: string };

const sameAddress = (a: string, b: string): boolean => a.replace(/\/+$/, '') === b.replace(/\/+$/, '');

/**
 * Merge the harness this app started into the configured endpoint list.
 *
 * A settings file written before the harness was bundled usually already holds an entry pointing at
 * `127.0.0.1:3002`. Adding the started harness as a *second* entry would list one host twice and open
 * its watch set twice — the duplicate-endpoint failure this project already paid for once. So an
 * entry for the same address is **relabelled, not duplicated**: the person's own name survives and
 * the running host's token wins, because it is the one that will answer.
 */
/**
 * Every state where a harness on this computer is answering and we hold its token.
 *
 * Three states, and the third is the one that used to fall through the list entirely:
 *
 * - `started` and `restarted` — we spawned it, so its token is ours to show and rotate.
 * - `attached` — it was already running when Ember launched (a `tinder setup --service` install, a
 *   container, a second window). Its lifecycle is not ours, so `canManageLocalToken` says no — but
 *   it is still **a host on this computer with a readable token**, and leaving it out of the
 *   endpoint list was the bug the owner hit: their settings held one remote endpoint, the local
 *   harness was attached rather than started, and Ember showed no local instance at all.
 */
export const isActiveHarness = (state: LocalHarnessState): state is Extract<LocalHarnessState, { token: string }> =>
  state.kind === 'started' || state.kind === 'restarted' || state.kind === 'attached';

/**
 * The narrower question: may this app give the host a *new* token?
 *
 * `attached` is the difference. That harness was already running when Ember launched — a service
 * install, a container, another window — so stopping and restarting it is not ours to do. It is
 * still `isActiveHarness` (listed, authenticated, usable), just not ours to re-key.
 */
export const isManagedHarness = (state: LocalHarnessState): state is Extract<LocalHarnessState, { token: string }> =>
  state.kind === 'started' || state.kind === 'restarted';

export const mergeLocalHarnessEndpoint = <T extends HarnessEndpoint>(
  configured: readonly T[],
  started: { url: string; token: string } | null
): T[] | HarnessEndpoint[] => {
  if (!started) return configured as T[];
  const match = configured.find((endpoint) => sameAddress(endpoint.url, started.url));
  if (match) {
    return configured.map((endpoint) => (endpoint === match ? { ...endpoint, token: started.token } : endpoint));
  }
  return [{ id: 'pi:local', label: 'This computer', url: started.url, token: started.token }, ...configured];
};
